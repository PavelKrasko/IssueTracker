export const ICON_NAMES = Object.keys(ICONS);

export function Icon({ name, className = "h-4 w-4", strokeWidth = 2 }) {
  const Component = ICONS[name];
  if (!Component) {
    if (import.meta.env.DEV) console.warn(`Иконка «${name}» не найдена — добавь её в components/icons/index.jsx`);
    return null;
  }
  return <Component aria-hidden="true" focusable="false" className={className} strokeWidth={strokeWidth} />;
}
